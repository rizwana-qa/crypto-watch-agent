# ---------------------------------------------------------------- one cell = one scenario for one coin
def run_cell(scenario, coin):
    rows_by_coin = {c: clean_rows(c) for c in COINS}
    rows_by_coin[coin] = json.loads(json.dumps(scenario.rows(coin, clean_rows(coin))))     # what Kraken would send, as JSON
    pair = agent.WATCHLIST[coin]
    calls = []

    def responder(*args, **kwargs):
        calls.append(kwargs)
        return scenario.kraken(coin, rows_by_coin[coin])(*args, **kwargs)

    # the production path for this coin: HTTP, parse, completed days
    agent_says, reason, errors, raw = "Pass", "", {}, {c: rows_by_coin[c] for c in COINS}
    with mock.patch.object(agent.requests, "get", side_effect=responder), mock.patch.object(agent.time, "sleep"):
        try:
            fetched = agent.fetch_rows(pair)
            raw[coin] = fetched
            agent.completed_closes(agent.parse_candles(fetched, pair), NOW)
        except (RuntimeError, ValueError) as error:
            agent_says, reason = "Reject", str(error)
            if isinstance(error, RuntimeError):
                errors[coin] = str(error)
                raw.pop(coin)

    if scenario.others_down:
        for other in COINS:
            if other != coin:
                errors[other] = f"{agent.WATCHLIST[other]}: request to Kraken failed after 3 attempts (ConnectionError)"
                raw.pop(other, None)

    # the audit for all three coins, the way validate_data.main builds it
    gecko = {c: coingecko_prices(clean_rows(c)) for c in COINS}
    if scenario.gecko != "ok":
        gecko[coin] = scenario.gecko(coin, rows_by_coin[coin])
    report = vd.validate(raw, NOW, gecko, errors)
    own = {r["check"]: r["status"] for r in report if r["coin"] == coin}
    across = {r["check"]: r["status"] for r in report if r["coin"] == "ALL"}
    audit = {**own, **across}
    statuses = set(audit.values())
    verdict = "Reject" if agent_says == "Reject" or vd.FAIL in statuses else "Warn" if vd.WARN in statuses else "Pass"

    problems = []
    if agent_says != scenario.agent:
        problems.append(f"agent gate said {agent_says} ({reason}), expected {scenario.agent}")
    for check, status in scenario.audit.items():
        if audit.get(check) != status:
            problems.append(f"audit {check} was {audit.get(check)}, expected {status}")
    if verdict != scenario.expected:
        problems.append(f"outcome was {verdict}, expected {scenario.expected}")
    for other in COINS:                         # a fault in one coin must never contaminate the others
        if other != coin and not scenario.others_down:
            bad = {r["check"]: r["status"] for r in report if r["coin"] == other and r["status"] != vd.PASS}
            if bad:
                problems.append(f"{other} was affected by a fault in {coin}: {bad}")
    if "coins_same_dates" not in scenario.audit and across.get("coins_same_dates") not in (vd.PASS, vd.SKIP):
        problems.append(f"the coins were reported as misaligned: {across}")
    if scenario.id == "FD-16" and len(calls) != 3:
        problems.append(f"expected 3 attempts at Kraken, saw {len(calls)}")
    if scenario.id == "FD-17" and len(calls) != 1:
        problems.append(f"expected 1 attempt at Kraken, saw {len(calls)}")
    for call in calls:
        if call.get("params") != {"pair": pair, "interval": 1440}:
            problems.append(f"the request to Kraken was {call.get('params')}")
    if scenario.extra:
        problems.extend(scenario.extra(coin, rows_by_coin))
    return Cell(scenario.id, coin, verdict, agent_says, reason, audit, problems)


_CELLS = None


def cells(force=False):
    """Every scenario for every coin it applies to, run once and cached."""
    global _CELLS
    if _CELLS is None or force:
        _CELLS = [run_cell(s, coin) for s in SCENARIOS for coin in s.coins]
    return _CELLS


# ---------------------------------------------------------------- measured coverage
def executable_lines(function):
    code, lines, stack = function.__code__, set(), [function.__code__]
    while stack:
        current = stack.pop()
        lines.update(line for _, _, line in current.co_lines() if line)
        stack.extend(const for const in current.co_consts if hasattr(const, "co_lines"))
    lines.discard(code.co_firstlineno)          # the def line runs when the module is imported
    return lines


GATE = [vd.fetch_coingecko, agent.fetch_rows, agent.fetch_candles, agent.as_number, agent.parse_candles, agent.completed_closes, agent.align_series,
        vd.check_rows, vd.check_coins_aligned, vd.check_against_coingecko, vd.coingecko_prices, vd.validate, vd.verdict, vd.num, vd.is_whole, vd.label, vd.examples]


def run_traced():
    """Run every scenario under Python's trace module. Returns (cells, {function name: (lines, missed lines)})."""
    tracer = trace.Trace(count=1, trace=0)
    result = tracer.runfunc(cells, True)
    hit = {}
    for (filename, line), _ in tracer.results().counts.items():
        hit.setdefault(filename, set()).add(line)
    coverage = {}
    for function in GATE:
        lines = executable_lines(function)
        coverage[f"{function.__module__}.{function.__name__}"] = (lines, lines - hit.get(function.__code__.co_filename, set()))
    return result, coverage


