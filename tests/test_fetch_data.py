def enforced_by(scenario):
    if scenario.expected == "Pass":
        return "Nothing reported"
    if scenario.agent == "Reject":
        return "Agent gate and audit"
    return "Audit only" if scenario.expected == "Reject" else "Audit warning"


def traces_to(scenario):
    checks = ", ".join(f"`{check}`" for check, status in scenario.audit.items() if status != vd.PASS)
    return f"{scenario.rule}" + (f"; audit {checks}" if checks else "")


def percent(lines, missed):
    return f"{100 * (1 - len(missed) / len(lines)):.0f}%"


def matrix_block(measured_cells, coverage):
    by = {(c.id, c.coin): c.verdict for c in measured_cells}
    lines = [START, "",
             "| ID | Scenario | Expected | Enforced by | BTC | ETH | XRP | Traces to (agent rule; audit check) |", "|---|---|---|---|---|---|---|---|"]
    for s in SCENARIOS:
        columns = [by.get((s.id, coin), "n/a") for coin in COINS]
        lines.append(f"| {s.id} | {s.title} | {s.expected} | {enforced_by(s)} | {columns[0]} | {columns[1]} | {columns[2]} | {traces_to(s)} |")
    total = len(measured_cells)
    ok = sum(1 for c in measured_cells if not c.problems)
    exercised = audit_checks_exercised()
    wanted = set(vd.COVERS)
    brief = [s for s in SCENARIOS if int(s.id[3:]) <= 12]
    lines += ["", "Measured coverage (from the run that produced this table):", "",
              f"- **Scenarios:** {len(SCENARIOS)}, of which {len(brief)} are from the brief (FD-01 to FD-12) and {len(SCENARIOS) - len(brief)} are added.",
              f"- **Scenario x coin cells run:** {total}. **As expected:** {ok} of {total}.",
              f"- **Audit checks that report a non-PASS in at least one scenario:** {len(exercised)} of {len(wanted)}"
              + ("." if exercised == wanted else f" (missing: {', '.join(sorted(wanted - exercised))})."),
              f"- **Executable lines run by the scenarios** (Python's `trace` module): " + ", ".join(
                  f"`{name.split('.', 1)[1]}` {percent(lines_, missed)}" for name, (lines_, missed) in coverage.items()) + ".",
              "", END]
    return "\n".join(lines)


_BLOCK = None


def current_block():
    """(markdown block, cells, line coverage) from one traced run, cached because tracing is slow."""
    global _BLOCK
    if _BLOCK is None:
        measured, coverage = run_traced()
        _BLOCK = (matrix_block(measured, coverage), measured, coverage)
    return _BLOCK


