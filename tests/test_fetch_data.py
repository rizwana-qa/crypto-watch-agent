def extra_all_three_align(coin, rows_by_coin):
    result = run_cross_asset(rows_by_coin)
    problems = []
    if result.get("coins") != list(COINS):
        problems.append(f"cross-asset coins were {result.get('coins')}")
    if len(result.get("correlations", [])) != 3 or result.get("as_of") != agent.format_date(TODAY - DAY) or "unavailable" in result:
        problems.append(f"cross-asset result was not complete for all three coins: {result}")
    return problems


def extra_one_coin_behind(coin, rows_by_coin):
    problems = []
    result = run_cross_asset(rows_by_coin)
    if coin not in result.get("unavailable", {}):
        problems.append(f"{coin} should be unavailable to the cross-asset tool, got {result.get('unavailable')}")
    if coin in result.get("coins", []) or any(coin in pair["pair"] for pair in result.get("correlations", [])):
        problems.append(f"{coin} must not appear in any correlation: {result}")
    # a caller that skipped the freshness check would hand align_series a coin that ends a day early
    series = {}
    for other in COINS:
        pair = agent.WATCHLIST[other]
        clean = clean_rows(other)
        series[other] = agent.completed_closes(agent.parse_candles(clean, pair), NOW)
    stamps, closes = series[coin]
    series[coin] = (stamps[:-1], closes[:-1])
    try:
        agent.align_series(series)
        problems.append("align_series accepted a coin that ends a day earlier than the others")
    except ValueError as error:
        if "different days" not in str(error) or coin not in str(error):
            problems.append(f"align_series refused for another reason: {error}")
    return problems


def extra_too_short_to_align(coin, rows_by_coin):
    """A coin with too few days must not be compared with the others, either through the tool or by a caller that skipped the history check."""
    problems = []
    result = run_cross_asset(rows_by_coin)
    if coin not in result.get("unavailable", {}):
        problems.append(f"{coin} should be unavailable to the cross-asset tool, got {result.get('unavailable')}")
    series = {}
    for other in COINS:
        series[other] = agent.completed_closes(agent.parse_candles(clean_rows(other), agent.WATCHLIST[other]), NOW)
    stamps, closes = series[coin]
    series[coin] = (stamps[-50:], closes[-50:])
    try:
        agent.align_series(series)
        problems.append("align_series accepted a coin with only 50 days")
    except ValueError as error:
        if "days in common" not in str(error):
            problems.append(f"align_series refused for another reason: {error}")
    return problems


