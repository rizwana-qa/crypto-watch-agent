def default_kraken(coin, rows):
    key = agent.RESULT_KEYS[agent.WATCHLIST[coin]]
    return lambda *args, **kwargs: reply(200, kraken_body(key, rows))


def wrong_pair_key(coin, rows):
    key = agent.RESULT_KEYS[agent.WATCHLIST[OTHER_KEY[coin]]]        # a valid key, but for another coin
    return lambda *args, **kwargs: reply(200, kraken_body(key, rows))


def always(response_factory):
    return lambda coin, rows: (lambda *args, **kwargs: response_factory())


def run_cross_asset(rows_by_coin):
    by_pair = {agent.WATCHLIST[c]: rows for c, rows in rows_by_coin.items()}
    with mock.patch.object(agent, "fetch_rows", side_effect=lambda pair: json.loads(json.dumps(by_pair[pair]))), \
            mock.patch.object(agent, "datetime", FrozenDatetime):
        return agent.tool_cross_asset_summary()


def gecko_points(coin, junk=True):
    """CoinGecko's /market_chart reply for the latest completed days, in milliseconds, with malformed points mixed in."""
    points = [[(r[0] + DAY) * 1000, float(r[C])] for r in clean_rows(coin) if TODAY - 14 * DAY <= r[0] < TODAY]
    if junk:
        points += [[1], "x", [(TODAY - DAY) * 1000 + 3_600_000, 5.0], [(TODAY - 20 * DAY) * 1000, 0], [True, 1.0], [(TODAY - 21 * DAY) * 1000, "abc"]]
    return {"prices": points}


