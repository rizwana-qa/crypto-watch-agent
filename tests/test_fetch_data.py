"""Fetch-data scenarios FD-01 to FD-45, each run for BTC, ETH and XRP, with a traceability matrix measured from the runs.

    python tests/test_fetch_data.py -v            run the scenarios (offline, no AI, no network)
    python tests/test_fetch_data.py --matrix      print the traceability matrix and the measured coverage as markdown
    python tests/test_fetch_data.py --write-readme   put that block into README.md (a test fails when the README is out of date)

FD-01 to FD-12 are the scenarios from the brief, with the same IDs and wording. FD-13 onwards are added to cover what the brief did not
name: the third coin, the whole fetch path (HTTP errors, a reply that is not JSON), every remaining kind of bad time, shape and value,
the warnings, and the second price source.

Every scenario goes through the real code path with a scripted Kraken: agent.fetch_rows (the HTTP layer, with a real requests.Response),
agent.parse_candles and agent.completed_closes (the agent's own gate), and then validate_data.validate (the audit). The coin under test
gets the fault, the other two coins stay clean and must stay clean. "Expected" is the outcome the brief asks for:
  Reject  the data is refused (agent gate, audit FAIL, or both),
  Warn    the data is accepted and the audit says look at it,
  Pass    the data is accepted and nothing is reported.
Coverage is measured, not claimed: scenarios x coins, the audit checks that report a non-PASS in at least one scenario, and the lines
of the data gate and the audit that the scenarios execute (Python's own trace module, no extra package).
"""

